# Only on Python before 3.12 (Blender 4.2), where the rule filter also refuses temp_override.
OVERRIDE_RULE = ("Never use bpy.context.temp_override: in this Blender it can crash while you work. Call "
                 "operators without it, or build with bpy.data and bmesh. Never call bpy.ops.object.quick_fur, "
                 "quick_explode, quick_smoke or quick_liquid: they use it inside.\n")


def system_text(text, blender=None, lines=STEP_LINES):
    """A stage's instructions, with ``OVERRIDE_RULE`` after the rules when this Python needs it. ``blender``: the
    version tuple; before 5 the Blender 4 notes replace the Blender 5 ones. ``lines``: the step size to ask for."""
    text = step_size(text, lines)
    if thread_safety.override_races():
        text = text.replace(_RULES, _RULES + OVERRIDE_RULE)
    if blender is not None and tuple(blender)[:1] < (5,):
        text = text.replace(_BLENDER_5, _BLENDER_4)
    return text
